#!/usr/bin/env python3
"""Render a Freqtrade Strategy Verification report from committed evidence.

The report is a pure function of a case file and the inputs it pins. Each input
is hash-checked first; a drifted input stops the run rather than producing a
report whose numbers no longer match its sources. No backtest runs here and
nothing is fetched: this is the rendering step only.

Usage:
    python3 verification/report.py                 # check the committed sample
    python3 verification/report.py --write         # regenerate it
    python3 verification/report.py --case C --out R

Exit codes: 0 report matches (or was written) · 1 report differs · 2 input drift.

PAPER / RESEARCH ONLY. REAL_MONEY_AUTHORIZED = NO.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import io
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
SAMPLE_CASE = REPO_ROOT / "verification" / "sample" / "case.json"
SAMPLE_REPORT = REPO_ROOT / "verification" / "sample" / "SAMPLE_REPORT.md"


class InputDrift(Exception):
    """An input's bytes no longer match the sha256 the case pins."""


def load_inputs(case: dict, root: Path) -> dict:
    loaded = {}
    for key, spec in case["inputs"].items():
        data = (root / spec["path"]).read_bytes()
        digest = hashlib.sha256(data).hexdigest()
        if digest != spec["sha256"]:
            raise InputDrift(f"{spec['path']}: sha256 {digest} != pinned {spec['sha256']}")
        text = data.decode("utf-8")
        loaded[key] = text if spec["path"].endswith(".csv") else json.loads(text)
    return loaded


def scorecard_row(text: str, candidate_id: str) -> dict:
    lines = [line for line in text.splitlines() if line and not line.startswith("#")]
    for row in csv.DictReader(io.StringIO("\n".join(lines))):
        if row["candidate_id"] == candidate_id:
            return row
    raise KeyError(f"no scorecard row for {candidate_id}")


def pct(value: float, signed: bool = False) -> str:
    return f"{value:+.2f}%" if signed else f"{value:.2f}%"


def pp(value: float) -> str:
    return f"{value:+.2f} pp"


def render(case: dict, root: Path = REPO_ROOT) -> str:
    i = load_inputs(case, root)
    source = i["pins"]["sources"][case["source_key"]]
    files = {f["path"]: f for f in source["files"]}
    claim = i["claims"][case["source_key"]]
    r = i["result"]["preserved_h1_evidence"]
    ev = i["evidence"]
    prov = ev["dataset_and_data_provenance"]
    engine = ev["engine_and_execution_environment"]
    row = scorecard_row(i["scorecard"], case["scorecard_candidate_id"])
    gates = i["gates"]["validity_gates"]["gates"]
    dataset = i["dataset"]
    passed = set(case["gates_recorded_pass"])
    c = r["controls"]

    out: list[str] = []
    w = out.append
    w(f"# Strategy Verification Report: {case['title']}")
    w("")
    w(f"Case `{case['case_id']}` · {case['kind'].replace('_', ' ').lower()} · generated by `verification/report.py` "
      "from committed evidence only.")
    w("")
    w("> This is a sample deliverable. It verifies a public strategy that its author published under "
      f"{source['license']['spdx']}. It is not affiliated with or endorsed by that author, it is not investment "
      "advice, and nothing here was traded with real money.")
    w("")

    w("## 1. Verdict")
    w("")
    w("```text")
    w(f"MEASUREMENT VALIDITY        {r['measurement_validity']}  (gates below; recorded, not re-run)")
    w(f"PUBLIC HEADLINE             NOT TESTED LIKE-FOR-LIKE  (upstream: ~8 years; this measurement: "
      f"{prov['timerange'][:10]} to {prov['timerange'][-20:-10]})")
    w(f"NET RETURN ON THIS WINDOW   {pct(r['net_return_pct'], True)} over {r['trades']} trades")
    w(f"VS BUY-AND-HOLD             {pp(r['excess_vs_buy_and_hold_pp'])}")
    w(f"VS EXPOSURE-MATCHED PASSIVE {pp(r['excess_vs_realised_exposure_matched_pp'])} (realised exposure) · "
      f"{pp(r['excess_vs_max_exposure_matched_pp'])} (max exposure)")
    w("EDGE                        NOT DEMONSTRATED  (result depends on which fair passive line is used)")
    w("```")
    w("")
    w("In plain terms: the strategy is measurable, it does not peek at future data on the checks that were run, "
      f"and it made {pct(r['net_return_pct'])} while Bitcoin itself rose {pct(c['btc_buy_and_hold_pct'])}. "
      "Most of its apparent safety comes from holding little capital in the market. Against a passive position "
      "that held the same realised exposure it is ahead; against one holding its peak exposure it is behind.")
    w("")

    w("## 2. What was verified")
    w("")
    w("| Component | Identity |")
    w("|---|---|")
    w(f"| Upstream repository | `{source['repo']}` at commit `{source['commit']}` |")
    for key in ("strategy_file", "params_file"):
        f = files[case[key]]
        w(f"| `{f['path']}` | sha256 `{f['sha256']}` |")
    lic = files["LICENSE"]
    w(f"| Licence | {source['license']['spdx']} · `LICENSE` sha256 `{lic['sha256']}` |")
    w(f"| Engine | `{engine['freqtrade_image']}` (pinned by tag, not by digest) |")
    w(f"| Market | {dataset['exchange']} {dataset['market_type']} · {', '.join(prov['pair_universe'])} · "
      f"{prov['timeframe']} candles |")
    w(f"| Data | `{dataset['dataset_id']}` · BTC/USDT 1h canonical sha256 "
      f"`{dataset['canonical_hashes']['BTC/USDT 1h']}` |")
    w(f"| Costs | fee {prov['fee_per_side'] * 100:.1f}% per side · wallet {prov['wallet']:.0f} USDT · spot, "
      "long only, no leverage |")
    w("")
    w("The parameter file matters as much as the source: Freqtrade loads it automatically, so the same `.py` with "
      "a different parameter file tests different rules. Both are pinned.")
    w("")

    w("## 3. What the author claims")
    w("")
    w(f"Read from the upstream README at the pinned commit (sha256 `{claim['readme_sha256']}`), before any result "
      "was produced here:")
    w("")
    a = claim["ablation_emacross_only"]
    w(f"- Stated conditions: {claim['stated_conditions']}.")
    w(f"- This strategy (EmaCross, the core without the funding rule): total return {a['total_return_pct']}%, "
      f"max drawdown {a['max_drawdown_pct']}%.")
    w(f"- Selection: picked from a {claim['benchmark_scale']['strategies_tested']}-strategy benchmark in which "
      f"{claim['benchmark_scale']['lost_money_outright']} lost money outright.")
    w("- The author's own stated weaknesses:")
    for name, text in claim["self_declared_weakness"].items():
        if name != "verified":
            w(f"  - {name.replace('_', ' ')}: {text}")
    w("")

    w("## 4. Independent measurement")
    w("")
    w("| Metric | Value |")
    w("|---|---|")
    w(f"| Net return | {pct(r['net_return_pct'], True)} |")
    w(f"| Trades | {r['trades']} |")
    w(f"| Win rate | {pct(r['win_rate_pct'])} |")
    w(f"| Profit factor | {r['profit_factor']:.2f} |")
    w(f"| Max drawdown | {pct(r['max_drawdown_pct'])} |")
    w(f"| Sharpe / Sortino | {r['sharpe']:.2f} / {r['sortino']:.2f} |")
    w(f"| Time in market | {pct(r['time_in_market_pct'])} |")
    w(f"| Average / peak capital exposure | {pct(float(row['avg_capital_exposure_pct']))} / "
      f"{pct(float(row['peak_capital_exposure_pct']))} |")
    w(f"| Fees paid | {float(row['fees_stake']):.2f} USDT |")
    w("")
    w("A 25% win rate with a profit factor above 2 is a trend-following profile: many small losses, few large "
      "wins. Win rate on its own says nothing about quality.")
    w("")

    w("## 5. Fair comparison")
    w("")
    w("A long-only strategy that sits in cash most of the time will look safe in any falling market. So the "
      "result is compared with passive positions that hold the same amount of capital, not only with raw "
      "buy-and-hold.")
    w("")
    w("| Passive line | Its return | Strategy minus line |")
    w("|---|---|---|")
    w(f"| BTC buy-and-hold, fully invested | {pct(c['btc_buy_and_hold_pct'], True)} | "
      f"{pp(r['excess_vs_buy_and_hold_pp'])} |")
    w(f"| Passive at the strategy's peak exposure | {pct(c['max_exposure_matched_pct'], True)} | "
      f"{pp(r['excess_vs_max_exposure_matched_pp'])} |")
    w(f"| Passive at the strategy's realised exposure | {pct(c['realised_exposure_matched_pct'], True)} | "
      f"{pp(r['excess_vs_realised_exposure_matched_pp'])} |")
    w("")

    w("## 6. Validity gates")
    w("")
    w("Pre-registered before any result existed. A gate failure means \"not measurable\", not \"bad\".")
    w("")
    w("| Gate | Question | Status |")
    w("|---|---|---|")
    for g in gates:
        status = "PASS (recorded)" if g["id"] in passed else "NOT RECORDED"
        w(f"| {g['id']} | {g['question']} | {status} |")
    w("")
    w(f"Source of the recorded statuses: {case['gates_source']}.")
    w("")

    w("## 7. Limits of this report")
    w("")
    w(f"- Reproducibility: `{ev['reproducibility_classification']['H1_REPRODUCIBILITY_PATH']}`. The run-level "
      "config hash was not recorded and the engine image is pinned by tag, not digest, so a rerun would be a "
      "controlled re-derivation, not a byte-exact reproduction.")
    w(f"- Trade-level ledger: {ev['trade_level_ledger']['status'].lower()}. Concentration (V8) could not be "
      "checked from preserved evidence.")
    w("- One pair, one window, backtest only. The author's 8-year headline was not re-run on its own window.")
    w("- Past performance in a backtest does not predict live results.")
    w("")

    w("## 8. Evidence")
    w("")
    w(f"Original measurement: GitHub Actions run {ev['source_identity']['run_id']}, job "
      f"{ev['source_identity']['job_id']}, artifact sha256 "
      f"`{ev['artifact_identity']['independently_recomputed_archive_sha256']}`.")
    w("")
    w("Inputs this report was rendered from:")
    w("")
    w("| Input | sha256 |")
    w("|---|---|")
    for spec in case["inputs"].values():
        w(f"| `{spec['path']}` | `{spec['sha256']}` |")
    w("")
    w("Regenerate and check: `python3 verification/report.py`")
    w("")
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--case", type=Path, default=SAMPLE_CASE)
    ap.add_argument("--out", type=Path, default=SAMPLE_REPORT)
    ap.add_argument("--write", action="store_true", help="write the report instead of checking it")
    args = ap.parse_args(argv)
    try:
        text = render(json.loads(args.case.read_text(encoding="utf-8")))
    except InputDrift as exc:
        print(f"REPORT = INPUT_DRIFT\n  - {exc}")
        return 2
    if args.write:
        args.out.write_text(text, encoding="utf-8")
        print(f"REPORT = WRITTEN {args.out}")
        return 0
    same = args.out.exists() and args.out.read_text(encoding="utf-8") == text
    print("REPORT = MATCHES" if same else "REPORT = DIFFERS; run with --write")
    return 0 if same else 1


if __name__ == "__main__":
    sys.exit(main())
